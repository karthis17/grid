export type MediaType = "image" | "video" | "vimeo";

export type VideoItem = {
  id: string;
  title: string;
  vimeoUrl: string;
  src?: string;
  no?: string;
  meta?: string;
  type?: MediaType;
  poster?: string;
  width?: number;
  height?: number;
  col?: number;
  row?: number;
  align?: "left" | "right";
  mobileCol?: number;
  mobileRow?: number;
  overlayColor?: string;
};

export type GalleryItem = {
  id: string;
  src: string;
  no: string;
  title: string;
  meta?: string;
  type?: MediaType;
  poster?: string;
  width?: number;
  height?: number;
  col?: number;
  row?: number;
  align?: "left" | "right";
  mobileCol?: number;
  mobileRow?: number;
  overlayColor?: string;
  vimeoUrl?: string;
};

const VIDEO_EXTENSIONS = /\.(mp4|webm|mov|m4v|ogg)$/i;

export function getMediaType(item: GalleryItem | VideoItem): MediaType {
  if (item.type) return item.type;
  if ("vimeoUrl" in item && item.vimeoUrl) return "vimeo";
  if (item.src && VIDEO_EXTENSIONS.test(item.src)) return "video";
  return "image";
}

